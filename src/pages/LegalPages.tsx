/** ช่องทางติดต่อ: ข้อความส่วนตัวถึงเพจ Facebook */
function Contact() {
  return FACEBOOK_PAGE_URL ? (
    <a href={FACEBOOK_PAGE_URL} target="_blank" rel="noopener noreferrer">
      ส่งข้อความถึง{SITE_OWNER}
    </a>
  ) : (
    <strong>ส่งข้อความส่วนตัวถึง{SITE_OWNER} บน Facebook</strong>
  );
}

function Back() {
  return (
    <button
      type="button"
      className="ph-btn ph-btn--sm ph-btn--light"
      onClick={() => (window.history.length > 1 ? window.history.back() : navigate("/"))}
    >
      ← กลับ
    </button>
  );
}

function Legal({ subtitle, children }: { subtitle: string; children: ReactNode }) {
  return (
    <>
      <StickerTitle top="เรียนย้อนหลัง" bottom="ฟิสิกส์" subtitle={subtitle} />
      <div className="ph-stack">
        <div>
          <Back />
        </div>
        <Card>
          <article className="ph-legal">
            {children}
            <p className="ph-small">ประกาศเมื่อ {LEGAL_UPDATED}</p>
          </article>
        </Card>
      </div>
    </>
  );
}

